"""Staged, atomic graph mutations matching the dashboard Division editor.

Builders perform no requests. Temporary references identify drafts within one
request; they become server UUIDs through the commit response's id_map. Detaching
an occurrence never permanently deletes the reusable child.
"""

from __future__ import annotations

from collections.abc import Mapping
from typing import Any, Literal
from uuid import uuid4

from pydantic import Field, model_validator

from .models import WireModel

ROOT_TYPES = {"division", "swift_agent", "flow_agent", "swift_chain", "flow_chain"}


class EntityRef(WireModel):
    """Reference a persisted object or a draft created in this request.

    Attributes:
        entity_type: Dashboard wire type, including source references for context.
        entity_id: Existing server UUID; defaults to None.
        temp_id: Request-local ID; defaults to None. Supply exactly one identifier.

    Raises:
        ValueError: Both identifiers, or neither identifier, are supplied.
    """

    entity_type: str
    entity_id: str | None = None
    temp_id: str | None = None

    @model_validator(mode="after")
    def validate_id(self) -> EntityRef:
        """Require exactly one identifier; source references are valid children."""
        if bool(self.entity_id) == bool(self.temp_id):
            raise ValueError("Exactly one of entity_id or temp_id is required")
        return self


class StepDependencyRef(WireModel):
    """Reference a persisted step or a draft step in an ordered collection.

    Attributes:
        step_id: Existing step UUID, default None.
        temp_id: New step correlation ID, default None. Supply exactly one ID.

    Raises:
        ValueError: Both identifiers, or neither identifier, are supplied.
    """

    step_id: str | None = None
    temp_id: str | None = None

    @model_validator(mode="after")
    def validate_id(self) -> StepDependencyRef:
        """Require exactly one step identifier."""
        if bool(self.step_id) == bool(self.temp_id):
            raise ValueError("Exactly one of step_id or temp_id is required")
        return self


class ChainStep(WireModel):
    """An ordered chain step with output visibility and explicit dependencies.

    Swift steps accept task agents or functions and dependency references. Flow
    steps accept conversational agents and optional forwarding functions. The
    dashboard validates the type-specific rules.

    Attributes:
        step_type: swift_agent, agentic_function, or flow_agent as appropriate.
        entity_ref: Reusable target, whose read permission is required if persisted.
        order_index: Zero-based, nonnegative position.
        step_id: Existing occurrence UUID to retain, default None.
        temp_id: New occurrence identifier for dependency references, default None.
        is_output_hidden_outside_the_chain: Hide this output, default False.
        is_dependent_to_main_chain_input: Include the chain input, default True.
        output_dependency_refs: Provider step references, default empty list.
        forward_agentic_function_ref: Optional Flow forwarding function, default None.
    """

    step_type: str
    entity_ref: EntityRef
    order_index: int = Field(ge=0)
    step_id: str | None = None
    temp_id: str | None = None
    is_output_hidden_outside_the_chain: bool = False
    is_dependent_to_main_chain_input: bool = True
    output_dependency_refs: list[StepDependencyRef] = Field(default_factory=list)
    forward_agentic_function_ref: EntityRef | None = None


class CreateEntityMutation(WireModel):
    """Typed entity creation; requires its family's write grant on commit.

    Attributes:
        op_id: Unique operation correlation ID, generated by default.
        entity_type: Dashboard entity wire type.
        temp_id: Request-local identifier, referenced by later operations.
        data: Writable entity profile, including supported nested fields.
        parent_context: Optional creation context understood by the dashboard.
    """

    op: Literal["create_entity"] = "create_entity"
    op_id: str = Field(default_factory=lambda: str(uuid4()))
    entity_type: str
    temp_id: str
    data: dict[str, Any]
    parent_context: dict[str, Any] | None = None


class PatchEntityMutation(WireModel):
    """Stage a typed partial update, including nested samples and parameters.

    Construction makes no request. Commit requires resource/root write and the
    grants for referenced children or removed sample resources.

    Attributes:
        op: Constant patch_entity operation code.
        op_id: Operation correlation UUID, generated by default.
        entity_type: Dashboard wire type of the edited entity.
        entity_id: Persisted server UUID.
        changes: Partial profile fields; nested dictionary None values are retained.
        expected_updated_at: Optional concurrency timestamp, default None.
    """

    op: Literal["patch_entity"] = "patch_entity"
    op_id: str = Field(default_factory=lambda: str(uuid4()))
    entity_type: str
    entity_id: str
    changes: dict[str, Any]
    expected_updated_at: str | None = None


class DeleteEntityMutation(WireModel):
    """Stage permanent deletion, requiring resource delete independently of root write.

    Construction makes no request. To remove a map occurrence, use RelationMutation
    with detach_relation instead. Delete a root Division through its direct API.

    Attributes:
        op: Constant delete_entity operation code.
        op_id: Operation correlation UUID, generated by default.
        entity_type: Dashboard wire type of the nested entity.
        entity_id: Persisted server UUID to permanently delete.
    """

    op: Literal["delete_entity"] = "delete_entity"
    op_id: str = Field(default_factory=lambda: str(uuid4()))
    entity_type: str
    entity_id: str


class RelationMutation(WireModel):
    """Typed attach/detach occurrence; parent write and existing child read are required.

    Detaching affects the relationship only. relation_data carries action settings
    and context metadata unchanged. Temporary children are references to creations
    in the same request, not persisted objects requiring independent read grants.

    Attributes:
        op: attach_relation or detach_relation.
        op_id: Operation correlation UUID, generated by default.
        relation: Server relation name.
        parent: Owner reference, requiring write on commit.
        child: Reusable target, requiring read if persisted.
        relation_data: Occurrence metadata, default empty mapping.
    """

    op: Literal["attach_relation", "detach_relation"]
    op_id: str = Field(default_factory=lambda: str(uuid4()))
    relation: str
    parent: EntityRef
    child: EntityRef
    relation_data: dict[str, Any] = Field(default_factory=dict)


class ReplaceCollectionMutation(WireModel):
    """Stage ordered step replacement, requiring chain write and existing target reads.

    Construction makes no request. Include every occurrence to retain; the
    replacement changes steps and dependencies while preserving reusable targets.

    Attributes:
        op: Constant replace_collection operation code.
        op_id: Operation correlation UUID, generated by default.
        relation: swift_chain_steps or flow_chain_steps.
        parent: Owning chain reference.
        items: Complete desired step collection; an empty list clears the chain.
    """

    op: Literal["replace_collection"] = "replace_collection"
    op_id: str = Field(default_factory=lambda: str(uuid4()))
    relation: Literal["swift_chain_steps", "flow_chain_steps"]
    parent: EntityRef
    items: list[ChainStep]


Mutation = (
    CreateEntityMutation
    | PatchEntityMutation
    | DeleteEntityMutation
    | RelationMutation
    | ReplaceCollectionMutation
)
"""Union of supported typed graph mutations; raw dictionaries remain accepted."""


class GraphMutationRequest(WireModel):
    """Dashboard mutation envelope, with atomic commit semantics.

    request_id is also sent as Idempotency-Key. The current server correlates it
    but does not guarantee deduplication. base_graph_revision is forwarded
    without changing the server's legacy handling of stale revisions.

    Attributes:
        request_id: Caller correlation ID; defaults to a new UUID.
        root: Existing or draft Division, agent, or chain root.
        base_graph_revision: Last observed revision; defaults to zero.
        commit_mode: Only atomic is supported; default atomic.
        operations: Nonempty typed operations or raw server dictionaries.

    Raises:
        ValueError: Root/mode is unsupported or operation IDs are missing/duplicated.
    """

    request_id: str = Field(default_factory=lambda: str(uuid4()))
    root: EntityRef
    base_graph_revision: int = 0
    commit_mode: str = "atomic"
    operations: list[Mutation | dict[str, Any]] = Field(min_length=1)

    @model_validator(mode="after")
    def validate_envelope(self) -> GraphMutationRequest:
        """Check root type, commit mode, and unique operation identifiers."""
        if self.root.entity_type not in ROOT_TYPES or self.commit_mode != "atomic":
            raise ValueError("A supported root and atomic commit mode are required")
        ids = [op.get("op_id") if isinstance(op, dict) else op.op_id for op in self.operations]
        if not all(ids) or len(set(ids)) != len(ids):
            raise ValueError("Operations require unique nonempty op_id values")
        return self


class GraphMutationBuilder:
    """Stage graph operations for explicit validation or atomic commit.

    Args:
        root: Existing root reference, or the draft root created by new_root().
        base_graph_revision: Revision from the saved map; defaults to zero.
        request_id: Optional stable correlation identifier.

    Example:
        >>> root = EntityRef(entity_type="division", entity_id="division-id")
        >>> graph = GraphMutationBuilder(root)
        >>> agent = graph.create_entity("swift_agent", {"name": "Support"})
        >>> graph.attach_relation("division_agents", root, agent) is graph
        True
    """

    def __init__(
        self,
        root: EntityRef,
        *,
        base_graph_revision: int = 0,
        request_id: str | None = None,
    ) -> None:
        """Initialize a local draft without reading or changing server state."""
        self.root = root
        self.base_graph_revision = base_graph_revision
        self.request_id = request_id or str(uuid4())
        self.operations: list[dict[str, Any]] = []

    @classmethod
    def new_root(cls, entity_type: str, data: Mapping[str, Any]) -> GraphMutationBuilder:
        """Create a builder that stages a new root and its initial profile.

        Requires the root family's write permission when committed. Returns the
        builder with a temporary root reference available as builder.root.

        Args:
            entity_type: division, swift_agent, flow_agent, swift_chain, or flow_chain.
            data: Initial profile fields; preserved without server-side changes.

        Returns:
            A local builder containing one create operation.

        Raises:
            ValueError: The entity type cannot be a graph root.
        """
        if entity_type not in ROOT_TYPES:
            raise ValueError("Unsupported graph root type")
        root = EntityRef(entity_type=entity_type, temp_id=f"tmp_{uuid4().hex}")
        builder = cls(root)
        builder.create_entity(entity_type, data, temp_id=root.temp_id)
        return builder

    def _add(self, operation: str, **fields: Any) -> GraphMutationBuilder:
        self.operations.append({"op_id": str(uuid4()), "op": operation, **fields})
        return self

    def create_entity(
        self,
        entity_type: str,
        data: Mapping[str, Any],
        *,
        temp_id: str | None = None,
        parent_context: Mapping[str, Any] | None = None,
    ) -> EntityRef:
        """Stage entity creation and return its temporary reference.

        Args:
            entity_type: Dashboard wire type, such as swift_agent or agentic_function.
            data: Writable entity profile, including nested configuration.
            temp_id: Optional request-local ID; generated when omitted.
            parent_context: Optional server-supported creation context.

        Returns:
            A reference for later attachment or dependency operations.

        Raises:
            ValueError: The temporary ID has already been used.

        Notes:
            Commit requires this family's write grant, root write, and read for
            referenced existing objects. This method only stages a local operation.
        """
        reference = EntityRef(entity_type=entity_type, temp_id=temp_id or f"tmp_{uuid4().hex}")
        if any(op.get("temp_id") == reference.temp_id for op in self.operations):
            raise ValueError("Duplicate temporary ID")
        fields: dict[str, Any] = {
            "entity_type": entity_type,
            "temp_id": reference.temp_id,
            "data": dict(data),
        }
        if parent_context is not None:
            fields["parent_context"] = dict(parent_context)
        self._add("create_entity", **fields)
        return reference

    def patch_entity(
        self,
        target: EntityRef,
        changes: Mapping[str, Any],
        *,
        expected_updated_at: str | None = None,
    ) -> GraphMutationBuilder:
        """Stage a partial update; edits to local drafts merge into their creation data.

        Requires the entity family's write grant. Existing samples, action
        options, LLM selection, and function parameters use server partial-update
        semantics. Omitted fields are not cleared.

        Args:
            target: Existing entity or a draft created by this builder.
            changes: Partial profile fields; explicit None values are preserved.
            expected_updated_at: Optional server concurrency timestamp, default None.

        Returns:
            This builder for chaining; no HTTP request occurs.

        Raises:
            ValueError: A draft target was not created in this builder.
        """
        if target.temp_id:
            for op in self.operations:
                if op.get("op") == "create_entity" and op.get("temp_id") == target.temp_id:
                    op["data"].update(changes)
                    return self
            raise ValueError("Draft reference was not created by this builder")
        fields: dict[str, Any] = {
            "entity_type": target.entity_type,
            "entity_id": target.entity_id,
            "changes": dict(changes),
        }
        if expected_updated_at is not None:
            fields["expected_updated_at"] = expected_updated_at
        return self._add("patch_entity", **fields)

    def delete_entity(self, target: EntityRef) -> GraphMutationBuilder:
        """Stage permanent deletion, requiring its family's delete grant.

        Use detach_relation for removing a map occurrence. Division deletion is
        performed through client.divisions.delete(), rather than graph mutations.

        Args:
            target: Persisted nested entity to permanently delete.

        Returns:
            This builder with a staged permanent delete.

        Raises:
            ValueError: Target is temporary or is a root Division.
        """
        if target.temp_id or target.entity_type == "division":
            raise ValueError("Delete persisted nested entities; delete Divisions through CRUD")
        return self._add(
            "delete_entity", entity_type=target.entity_type, entity_id=target.entity_id
        )

    def attach_relation(
        self,
        relation: str,
        parent: EntityRef,
        child: EntityRef,
        *,
        relation_data: Mapping[str, Any] | None = None,
    ) -> GraphMutationBuilder:
        """Stage an attachment, requiring parent write and existing-child read access.

        relation_data preserves action type, visibility, augmentation, or other
        relation metadata. Reusing a child shares that entity; it does not clone it.

        Args:
            relation: Server relation name, such as division_agents or agent_actions.
            parent: Owner reference; requires write when committed.
            child: Reusable target; persisted targets require read when committed.
            relation_data: Occurrence settings, default empty mapping.

        Returns:
            This builder; no HTTP request occurs.
        """
        return self._add(
            "attach_relation",
            relation=relation,
            parent=parent.model_dump(exclude_none=True),
            child=child.model_dump(exclude_none=True),
            relation_data=dict(relation_data or {}),
        )

    def detach_relation(
        self,
        relation: str,
        parent: EntityRef,
        child: EntityRef,
        *,
        relation_data: Mapping[str, Any] | None = None,
    ) -> GraphMutationBuilder:
        """Remove an exact relationship occurrence without deleting its reusable child.

        Requires parent write and existing-child read access. Use the parent and
        relationship IDs from the map to distinguish repeated occurrences/loops.

        Args:
            relation: Server relation name of the occurrence to remove.
            parent: Owner reference; requires write when committed.
            child: Reusable target; requires read if persisted.
            relation_data: Exact occurrence metadata when needed, default empty mapping.

        Returns:
            This builder with a staged relationship removal.
        """
        return self._add(
            "detach_relation",
            relation=relation,
            parent=parent.model_dump(exclude_none=True),
            child=child.model_dump(exclude_none=True),
            relation_data=dict(relation_data or {}),
        )

    def replace_collection(
        self,
        relation: str,
        parent: EntityRef,
        items: list[ChainStep | Mapping[str, Any]],
    ) -> GraphMutationBuilder:
        """Replace all chain steps atomically, including order and dependency references.

        Only swift_chain_steps and flow_chain_steps are supported. An empty list
        clears the chain. Existing step IDs must be included to preserve them.
        Requires chains:write and read grants for existing referenced entities.

        Args:
            relation: swift_chain_steps or flow_chain_steps.
            parent: Owning chain reference.
            items: Complete desired ordered collection, including dependency metadata.

        Returns:
            This builder with a staged collection replacement.

        Raises:
            ValueError: The relation is not an ordered chain-step collection.
        """
        if relation not in {"swift_chain_steps", "flow_chain_steps"}:
            raise ValueError("Only ordered chain-step collections can be replaced")
        return self._add(
            "replace_collection",
            relation=relation,
            parent=parent.model_dump(exclude_none=True),
            items=[
                item.model_dump(exclude_none=True) if isinstance(item, ChainStep) else dict(item)
                for item in items
            ],
        )

    def build(self) -> GraphMutationRequest:
        """Return a deep snapshot without making an API request.

        Returns:
            A typed request independent of subsequent edits to this builder.

        Raises:
            ValueError: No operations were staged or the envelope is invalid.
        """
        import copy

        return GraphMutationRequest(
            root=self.root.model_copy(deep=True),
            request_id=self.request_id,
            base_graph_revision=self.base_graph_revision,
            operations=[copy.deepcopy(op) for op in self.operations],
        )
